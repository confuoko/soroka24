"""Базовый интерфейс парсера карточки дела.

Парсер — чистое преобразование HTML в данные: ни БД, ни сети, ни выбора прокси, ни
разгадывания капчи. Он не знает, с какого портала пришла страница и как её добыли.

Под каждую ВЁРСТКУ страницы — свой класс. Не под портал: один и тот же движок msudrf.ru
отдаёт две разные вёрстки (типы B и C), и разбирают их разные парсеры, хотя ходит на
портал один и тот же клиент.

Контракт вывода описан не здесь, а типами: см. ParsedCase в app/parsers/parsed_case.py.
В старом core на его месте был обычный dict, а форма жила в докстринге на 70 строк.

Одно требование, которого нет в подписи, но которое обязаны соблюдать все парсеры:
**на незнакомом или недорендеренном документе parse не падает, а возвращает пустой
ParsedCase.** Браузер иногда отдаёт <html><head></head><body></body></html>, и разбор
такой страницы обязан быть пустым, а не исключением.
"""
from abc import ABC, abstractmethod

from app.parsers.parsed_case import ParsedCase


class UnsupportedPage(Exception):
    """Разбирать эту страницу нечем: вёрстка не опознана.

    Отказ ОКОНЧАТЕЛЬНЫЙ — повторный поход отдаст ту же самую страницу. Значит это
    либо не карточка дела, либо портал сменил разметку и нужен новый парсер.

    В старом core этой ошибки не существовало: клиент нёс ожидаемую вёрстку в
    константе класса, и при неопознанной разметке страница разбиралась ожидаемым
    парсером. Разбор выходил пустым, и его отсекала проверка «пустой разбор» уже в
    Celery-задаче. Итог был тот же — окончательный отказ, — но назывался он «не
    удалось разобрать», и понять по нему, что портал сменил вёрстку, было нельзя.
    """



class CaseParser(ABC):
    """Интерфейс парсера.

    page_type — обозначение вёрстки: A (мировые суды Москвы), B и C (две вёрстки движка
    msudrf.ru), D (Петербург).
    """

    page_type: str

    @abstractmethod
    def parse(self, html: str) -> ParsedCase:
        """Разобрать HTML карточки в данные дела."""
