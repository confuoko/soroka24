"""Публичный контракт изменений: то, что уезжает наружу через RabbitMQ.

Вторая таблица рядом с outbox_event, и это сознательное дублирование. Причина одна и она
решающая:

**payload домен-лога меняется всякий раз, когда парсер начинает отдавать новое поле, а
клиентский сервис от таких правок ломаться не должен.**

Поэтому наружу уходит отдельное, намеренно скудное представление: что за изменение, по
какому делу, у какой сущности, когда обнаружено. Всё. Полные судебные данные клиент при
необходимости берёт по HTTP (GET /cases/{id}), где формат ответа — тоже наш публичный
контракт, но уже версионируемый отдельно.

## Почему не одна таблица с published_at

Потому что у двух таблиц разные работы, и склеивать их значит связать публичный контракт
с внутренним:

    outbox_event               домен-лог: append-only, богатый payload, читается по HTTP
                               курсором по created_at, ничего не знает о доставке
    integration_outbox_event   очередь на публикацию: скудная, обновляемая (published_at),
                               читается только своим publisher'ом

Плюс практическое: append-only у outbox_event — заявленный инвариант (см. его докстринг и
ARCHITECTURE.md §22), а очереди на публикацию UPDATE нужен по определению.

## Схема — это и есть контракт

Колонки здесь ровно те, что уезжают в JSON, поэтому payload-колонки нет: добавить поле в
сообщение нельзя, не добавив его в схему, и наоборот. JSONB позволил бы менять формат
молча — именно того, от чего эта таблица и защищает.

    {"id": 1502, "type": "event_new", "version": 1,
     "case_id": 481, "entity_id": 712, "occurred_at": "2026-08-23T13:20:00Z"}
"""
from datetime import datetime
from typing import Optional

from sqlalchemy import BigInteger, ForeignKey, Index, SmallInteger, String, func, text
from sqlalchemy.orm import Mapped, mapped_column

from app.database import UTC_DATETIME, Base
from app.models.case import Case  # noqa: F401 — держит порядок создания таблиц


class IntegrationOutboxEvent(Base):
    """Одно изменение, готовое к публикации наружу (transactional outbox).

    Пишется в ТОЙ ЖЕ транзакции, что и само изменение карточки и строка домен-лога
    (см. app/services/discovery.py). Отсюда два свойства, ради которых всё и сделано:

    * сообщение не может потеряться — оно коммитится вместе с изменением;
    * сообщение не может появиться без изменения — откат уносит и то, и другое.

    Доставка **at-least-once, и это не недоделка.** Публикация в брокер и UPDATE
    published_at — две разные операции, между ними процесс может умереть, и тогда
    сообщение уедет повторно. Exactly-once здесь не построить без распределённой
    транзакции с брокером; вместо этого читающий обязан быть идемпотентным — у него для
    этого есть id этой строки, уникальный и неизменный.
    """

    __tablename__ = "integration_outbox_event"

    __table_args__ = (
        # Частичный индекс под единственный запрос publisher'а: «что ещё не опубликовано,
        # по порядку». Частичный — потому что опубликованное составит 99.99% таблицы и
        # publisher'у оно неинтересно навсегда.
        Index(
            "ix_integration_outbox_unpublished",
            "id",
            postgresql_where=text("published_at IS NULL"),
        ),
    )

    # Он же id сообщения в JSON и integration_event_id на стороне клиента: там на нём
    # держится идемпотентность повторной доставки. Поэтому строки не переиспользуются и
    # id никогда не меняется.
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)

    # Тип изменения СТРОКОЙ, а не Enum, и это не небрежность. Enum в БД означал бы, что
    # переименование внутреннего OutboxEventType требует миграции публичной таблицы, —
    # то есть внутреннее устройство core снова протекло бы в контракт. Соответствие
    # «внутренний тип → публичное имя» задано явной таблицей в app/integration_events.py,
    # и её полноту проверяет тест.
    event_type: Mapped[str] = mapped_column(String(32), index=True)

    # Дело, по которому обнаружено изменение. Удалили дело — уносим и неопубликованные
    # сообщения по нему: рассказывать про изменения в деле, которого больше нет, незачем.
    case_id: Mapped[int] = mapped_column(
        ForeignKey("case.id", ondelete="CASCADE"), index=True
    )

    # id изменившейся строки: события «Движения дела», заседания, документа, судьи,
    # стороны. NULL у case_field_changed — там изменилась сама карточка, и её id уже есть
    # в case_id.
    #
    # Клиенту он нужен, чтобы показать «вот ЭТО новое», а не «в деле что-то поменялось».
    entity_id: Mapped[Optional[int]] = mapped_column(BigInteger, nullable=True)

    # Версия контракта. Нужна ровно тогда, когда формат сообщения придётся менять
    # несовместимо: клиент увидит незнакомую версию и сможет отказаться её разбирать
    # вместо того, чтобы молча прочитать поля неправильно.
    version: Mapped[int] = mapped_column(
        SmallInteger, nullable=False, server_default=text("1")
    )

    # Когда изменение ОБНАРУЖЕНО (момент коммита обхода). Отдельной колонки created_at
    # здесь нет намеренно: она означала бы то же самое. Момент один, и назван он по
    # смыслу, а не по механике записи.
    occurred_at: Mapped[datetime] = mapped_column(
        UTC_DATETIME, server_default=func.now()
    )

    # Когда сообщение ушло в брокер. NULL — ещё не ушло, и именно это ищет publisher.
    #
    # Состояние доставки живёт ЗДЕСЬ и только здесь. В outbox_event его нет и не будет:
    # это домен-лог, и пометка «отправлено» в нём смешала бы судебный факт с делами
    # инфраструктуры.
    published_at: Mapped[Optional[datetime]] = mapped_column(
        UTC_DATETIME, nullable=True
    )

    def __str__(self) -> str:
        state = "опубликовано" if self.published_at else "ждёт публикации"
        return f"{self.event_type} по делу #{self.case_id} ({state})"
