"""Клиент суда: как добраться до страницы дела. Общая часть.

Клиент отвечает на ОДИН вопрос: **как получить страницу карточки с этого портала?**
Навигация, формы поиска, капча, прокси, cookies, ошибки транспорта, повторы — его дело.

Чего клиент НЕ делает (и это главное отличие от старого core):

* не выбирает парсер;
* не вызывает парсер;
* не разбирает содержимое страницы — ни судью, ни события, ни стороны.

Из этого следует правило, которое стоит запомнить:

    **Клиент соответствует СПОСОБУ ДОСТУПА к порталу, а не вёрстке страницы.**

Движок msudrf.ru отдаёт две разные вёрстки карточки (типы B и C), но ходить на него надо
одинаково: тот же адрес, та же капча, тот же невалидный сертификат. Поэтому клиент один,
а парсера два. Если завтра появится третья вёрстка, добавится третий парсер — и ни одного
нового клиента, потому что способ получить страницу не изменился.

В старом core здесь было два класса, MsudrfCourtClient и MsudrfTypeCCourtClient, и второй
целиком состоял из одной строки `page_type = "C"`.
"""
import re
from abc import ABC
from dataclasses import dataclass

from app.browser import ChromiumSession

# УИД дела в тексте страницы: 50MS0095-01-2026-002990-16. Формат общероссийский,
# поэтому поиск один на все порталы — от вёрстки он не зависит вовсе.
UID_RE = re.compile(r"\b\d{2}[A-Z]{2}\d{4}-\d{2}-\d{4}-\d{6}-\d{2}\b")


def find_uid(html: str) -> str | None:
    """Найти УИД дела в разметке страницы (или None, если его там нет).

    Обычная функция, а не метод клиента и не класс-извлекатель: правило одно на всю
    страну, состояния у него нет, и зависеть от портала ему незачем.
    """
    found = UID_RE.search(html)
    return found.group(0) if found else None


@dataclass(frozen=True)
class PageSnapshot:
    """Снимок страницы, на которой мы упали: чем сайт ответил в момент отказа.

    Снимать его можно ТОЛЬКО внутри ChromiumSession, пока браузер жив: как только клиент
    вышел из своего `with`, страницы уже нет. Поэтому клиент прикладывает снимок к
    исключению, а сохраняет его в S3 уже вызывающий код.

    url и status важны не меньше разметки: редирект на страницу блокировки виден по url,
    а 403 — по статусу, даже если тело выглядит как обычная страница.
    """

    html: str
    url: str | None = None
    status: int | None = None


@dataclass(frozen=True)
class FetchedCard:
    """Страница карточки плюс то, что стало известно о ней ПО ХОДУ НАВИГАЦИИ.

    Смысл этих полей — не выбрасывать то, что портал уже сказал. Поиск по УИД на
    mos-sud.ru отдаёт таблицу, и номер дела с номером участка стоят прямо в её строке,
    то есть известны РАНЬШЕ, чем откроется сама карточка. Это важно: и номер, и суд входят
    в ключ карточки, а на самой странице номер приходит под разными метками и потому не
    всегда, суда же там нет вовсе. Выбросить их и потом выковыривать из HTML — значит
    сделать лишнюю работу и местами не сделать её вообще.

    В старом core fetch_case_html_by_url возвращал голую строку HTML, и вызывающий код
    собирал карточку обратно вручную, таская адрес и статус отдельными переменными.

    Что чем заполняется:

    * html          — всегда;
    * case_code     — только там, где номер известен из навигации (таблица результатов
                      поиска Москвы). У msudrf и Петербурга номер лежит в самой странице,
                      и его достают отдельные функции extract_*_case_code;
    * participok_no — номер судебного участка из ссылки. Есть у Москвы (из href строки
                      таблицы) и у Петербурга (из пути адреса); у msudrf участок
                      определяется по субдомену, то есть по справочнику;
    * source_url    — адрес, по которому карточка открыта, если он был известен заранее.
                      У московской ветки остаётся None: старый core адреса этих карточек
                      не записывал, и заполнить его здесь значило бы завести делам Москвы
                      строки в case_url, которых у них раньше не было. Это отдельное
                      изменение поведения, и его место не в переносе;
    * status        — HTTP-статус страницы карточки, если его удалось увидеть;
    * captchas_solved — сколько платных капч ушло на эту карточку. Нужно для учёта
                      стоимости; у порталов без капчи всегда 0.
    """

    html: str
    case_code: str | None = None
    participok_no: int | None = None
    source_url: str | None = None
    status: int | None = None
    captchas_solved: int = 0


class CourtError(Exception):
    """Базовая ошибка при работе с судом.

    page — снимок страницы отказа, если его удалось снять (иначе None).
    """

    def __init__(self, *args, page: PageSnapshot | None = None) -> None:
        super().__init__(*args)
        self.page = page


class UnsupportedCourt(CourtError):
    """Портал не поддержан: ни по префиксу УИД, ни по хосту ссылки его не узнали."""


class CaseNotFound(CourtError):
    """Страница открылась, но карточки дела на ней нет.

    Отказ ОКОНЧАТЕЛЬНЫЙ: дело сняли с публикации, либо поехала разметка. Повторять
    бессмысленно, поэтому вызывающий код такие ошибки не ретраит.
    """


class FetchFailed(CourtError):
    """Не удалось добраться до карточки (таймаут, капча, поменялась разметка).

    Отказ ВРЕМЕННЫЙ: вызывающий код его ретраит. Оборачивает исходное исключение, чтобы
    к нему можно было приложить снимок страницы.
    """

    def __init__(
        self, uid: str, reason: BaseException, page: PageSnapshot | None = None
    ) -> None:
        super().__init__(f"{uid}: {reason}", page=page)
        self.uid = uid
        self.reason = reason


# Статусы, при которых повторить попытку осмысленно: портал лёг (5xx), нас притормозили
# (429) или отсекли по IP (403). Проверять их приходится вручную: для Playwright любой
# ответ сервера — успешная навигация, исключение он бросает только на сетевых отказах.
# Без явной проверки страница ошибки молча уезжала бы в парсер, а тот падал бы с
# неретраибельной ошибкой разбора — то есть временный сбой хоронил бы задачу навсегда.
RETRYABLE_STATUSES = frozenset({403, 429})


def capture_page(session: ChromiumSession, status: int | None) -> PageSnapshot | None:
    """Снять страницу для разбора отказа. Само снятие не должно ронять ничего сверху.

    Браузер в момент отказа может быть уже нездоров (упал контекст, повисла вкладка),
    поэтому любую ошибку снятия глотаем: исходная причина отказа важнее снимка.
    """
    try:
        return PageSnapshot(html=session.content(), url=session.page.url, status=status)
    except Exception:
        return None


def is_retryable_status(status: int | None) -> bool:
    """Портал ответил так, что имеет смысл прийти ещё раз (и с другого прокси)?"""
    return status is not None and (status >= 500 or status in RETRYABLE_STATUSES)


def check_status(
    session: ChromiumSession, uid: str, status: int | None, where: str
) -> None:
    """Упасть сразу, если портал ответил ошибкой, — не дожидаясь таймаута.

    Иначе клиент искал бы элементы на странице ошибки все 30 секунд, а в тексте отказа
    оставался бы бесполезный «Page.fill: Timeout» вместо честного кода ответа.

    Снимок снимаем только при отказе: карточка дела весит под полмегабайта, и дёргать
    page.content() на каждой удачной навигации незачем.
    """
    if is_retryable_status(status):
        raise FetchFailed(
            uid,
            RuntimeError(f"{where} ответила HTTP {status}"),
            page=capture_page(session, status),
        )


class CourtClient(ABC):
    """Интерфейс клиента суда.

    portal — ключ портала (mos-sud / msudrf / spb). По нему пул выдаёт прокси, который до
    этого портала действительно доходит: провайдеры режут CONNECT выборочно, и адрес,
    берущий mos-sud, до msudrf может не дойти вовсе. Те же ключи у проб в
    app/courts/site_probe.py — они и заполняют Proxy.portals.

    Обратите внимание: page_type у клиента больше НЕТ. Вёрстка — свойство страницы, а не
    способа до неё добраться, и определяется она по самой странице (detect_page_type).

    Конструктор наследника обязан принимать два именованных аргумента:

    * proxy (ProxySettings | None) — арендованный из пула прокси. На портал суда клиент
      должен ходить только через него. Арендует его НЕ клиент: решение «каким прокси
      идти» принимает тот, кто запускает поход (app/services/proxy_pool.py);
    * on_captcha_attempt (AttemptSink | None) — куда сообщать о каждой оплаченной капче.
      Клиенты порталов без капчи аргумент принимают и игнорируют: сигнатура у всех
      клиентов общая, а сам учёт ведёт вызывающий код (он знает про БД, клиент нет).

    Входов в карточку два, и у разных порталов работает разный:

    * fetch_cases_by_uid — у портала есть поиск по УИД (так устроена Москва). Отдаёт
      СПИСОК: по одному УИД портал показывает таблицу, и дел в ней может быть несколько;
    * fetch_card_by_url — поиска нет, зато карточка открывается по прямой ссылке (так
      устроены msudrf.ru и Петербург). Отдаёт одну карточку.

    Реализовать нужно только тот, который портал поддерживает: у второго остаётся отказ
    по умолчанию. Абстрактных методов здесь нет намеренно — иначе каждый клиент был бы
    обязан заглушить чужой вход.
    """

    portal: str

    def fetch_cases_by_uid(self, uid: str) -> list[FetchedCard]:
        """Найти по УИД все дела портала и вернуть их карточки."""
        raise UnsupportedCourt(f"{type(self).__name__} не умеет искать дело по УИД")

    def fetch_card_by_url(self, url: str) -> FetchedCard:
        """Открыть карточку дела по прямой ссылке."""
        raise UnsupportedCourt(f"{type(self).__name__} не умеет открывать дело по ссылке")
