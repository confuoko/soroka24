"""Чем опознавать карточку дела: УИД и номер дела.

Ключ карточки — тройка «УИД + суд + номер дела» (`Case.card_key`). От него считаются
детерминированные uid всех дочерних строк: событий, документов, заседаний,
местонахождений. Поэтому здесь самое чувствительное место всего сервиса: сменить ключ
существующей карточки — значит перестать узнавать её дочерние строки и получить волну
ложных удалений и вставок.

Три обычные функции и никаких классов. Ни `CardIdentityExtractor`, ни `UidResolver`,
ни фабрик: у задачи нет ни состояния, ни нескольких реализаций, которым нужен общий
контракт.

Кто откуда берётся:

    суд         — по справочнику (app/repositories/courts.py): по номеру участка из
                  таблицы результатов поиска либо по хосту ссылки. НИКОГДА не из УИД:
                  участок № 463 — это код суда 77MS0466, а 77MS0463 — совсем другой суд;
    номер дела  — из навигации, если портал сказал его до открытия карточки (Москва),
                  иначе из заголовка страницы;
    УИД         — см. resolve_case_uid: сохранённый важнее найденного на странице.
"""
import logging

from sqlalchemy.orm import Session

from app.courts import CaseNotFound, FetchedCard, find_uid
from app.courts.msudrf import extract_msudrf_case_code
from app.courts.spb import extract_spb_case_code
from app.repositories import CaseRepository
from app.validators import synthetic_uid

logger = logging.getLogger(__name__)


def resolve_case_code(portal: str, fetched: FetchedCard) -> str:
    """Номер дела: взять уже известный из навигации либо достать из заголовка страницы.

    Порядок именно такой, и первый шаг важнее, чем кажется. Поиск по УИД на mos-sud.ru
    отдаёт таблицу, где номер дела стоит прямо в строке — то есть известен ДО открытия
    карточки. На самой карточке он подписан по-разному в зависимости от вида производства
    («Номер дела» у КоАП, «Номер заявления» у гражданских), поэтому доставать его оттуда
    повторно значит делать лишнюю работу и местами не сделать её вовсе.

    У msudrf и Петербурга навигация номера не знает — он только в заголовке страницы.

    Номер входит в ключ карточки, поэтому без него дело не сохранить: отсутствие
    заголовка означает, что открылась не карточка, и повторять поход бессмысленно.
    """
    if fetched.case_code:
        return fetched.case_code

    if portal == "msudrf":
        return extract_msudrf_case_code(fetched.html)

    if portal == "spb":
        return extract_spb_case_code(fetched.html)

    raise CaseNotFound(
        f"Портал {portal!r} не сказал номер дела при навигации, "
        "а доставать его со страницы этого портала мы не умеем"
    )


def resolve_case_uid(
    session: Session, html: str, source_url: str, court_code: str
) -> str:
    """Чем опознавать карточку, пришедшую ссылкой. Три шага, порядок обязателен.

    1. **Карточка по этой ссылке в базе уже есть — берём ЕЁ УИД и не меняем никогда.**
       Это главное, что делает самодельный ключ безопасным. Портал может позже
       дозаполнить УИД у дела, которое мы завели, когда УИД на странице не было. Смени
       мы ключ — uid событий, документов, заседаний и местонахождений перестали бы
       совпадать с сохранёнными, и обход выдал бы «всё удалено, всё создано заново».
       Заодно поехал бы путь снимков страницы в S3.
    2. **На странице есть настоящий УИД — берём его.** Он сквозной и связывает карточки
       одного дела в разных инстанциях, поэтому предпочтителен всегда, когда есть.
    3. **УИД на странице нет вовсе — считаем ключ сами от ссылки.** Так устроены
       архивные дела движка msudrf.ru и целые регионы вроде Магаданской области.
       Наружу такой ключ не отдаётся, см. `Case.public_uid`.

    Доказательство того, что открылась именно карточка, — НЕ наличие УИД, а номер дела:
    его достаёт resolve_case_code, и он падает с CaseNotFound, если заголовка на
    странице нет.

    Отличие от старого core: сессия приходит аргументом, а не открывается внутри.
    Читать «а нет ли уже такой карточки» и потом писать эту карточку осмысленно в одной
    транзакции, и решать это должен вызывающий, а не хелпер.
    """
    known = CaseRepository(session).get_by_url(source_url)
    known_uid = known.uid if known is not None else None
    page_uid = find_uid(html)

    if known_uid is not None:
        if page_uid is not None and page_uid != known_uid:
            # Чаще всего это ровно тот случай, ради которого шаг 1 и написан: карточку
            # заводили, когда УИД на странице не было, а теперь портал его дозаполнил.
            logger.warning(
                "Ссылка %s: на странице УИД %s, а ключ карточки остаётся %s",
                source_url,
                page_uid,
                known_uid,
            )
        return known_uid

    if page_uid is not None:
        return page_uid

    uid = synthetic_uid(court_code, source_url)
    logger.info(
        "Ссылка %s: УИД на странице нет — карточка сохраняется под ключом %s",
        source_url,
        uid,
    )
    return uid
