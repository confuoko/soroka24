"""Валидация входных данных, не зависящая от БД и HTTP.

Пока здесь — проверка УИД дела (уникального идентификатора).
"""
import re

# Формат УИД: 77MS0466-01-2026-003751-93
# 2 цифры (регион) + 2 буквы (тип суда) + 4 цифры, затем блоки через дефис.
UID_PATTERN = re.compile(r"^\d{2}[A-Z]{2}\d{4}-\d{2}-\d{4}-\d{6}-\d{2}$")


def normalize_uid(uid: str) -> str:
    """Привести УИД к каноническому виду: убрать пробелы, буквы — в верхний регистр."""
    return (uid or "").strip().upper()


def validate_uid(uid: str) -> bool:
    """Проверить формат УИД дела (например, 77MS0466-01-2026-003751-93)."""
    return bool(UID_PATTERN.match(normalize_uid(uid)))
