"""Валидация входных данных, не зависящая от БД и HTTP.

Здесь же разбор того, что прислал пользователь: УИД дела или ссылку на карточку.
"""
import hashlib
import re
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

# Формат УИД: 77MS0466-01-2026-003751-93
# 2 цифры (регион) + 2 буквы (тип суда) + 4 цифры, затем блоки через дефис.
UID_PATTERN = re.compile(r"^\d{2}[A-Z]{2}\d{4}-\d{2}-\d{4}-\d{6}-\d{2}$")


def normalize_uid(uid: str) -> str:
    """Привести УИД к каноническому виду: убрать пробелы, буквы — в верхний регистр."""
    return (uid or "").strip().upper()


def validate_uid(uid: str) -> bool:
    """Проверить формат УИД дела (например, 77MS0466-01-2026-003751-93)."""
    return bool(UID_PATTERN.match(normalize_uid(uid)))


def normalize_url(url: str) -> str:
    """Убрать пробелы по краям. Регистр НЕ трогаем: в пути и параметрах он значим."""
    return (url or "").strip()


def looks_like_url(value: str) -> bool:
    """Это ссылка, а не УИД?

    Проверяем по схеме, а не по наличию точки: УИД точек не содержит, но ошибиться
    в другую сторону легко, а дальше разное поведение — искать дело поиском или
    открывать прямой адрес.
    """
    return normalize_url(value).lower().startswith(("http://", "https://"))


def validate_url(url: str) -> bool:
    """Проверить, что ссылка похожа на адрес карточки дела: есть схема и хост."""
    parts = urlsplit(normalize_url(url))
    return parts.scheme in ("http", "https") and bool(parts.hostname)


# Параметры, которые действительно определяют карточку дела на порталах судов.
# Всё остальное (счётчики переходов, метки рассылок, мусор из адресной строки) на то,
# какая это карточка, не влияет и только мешает узнавать одну и ту же ссылку.
#
# Список — объединение по всем поддержанным порталам, и добавлять сюда параметр нового
# портала ОБЯЗАТЕЛЬНО: выброшенный значащий параметр не просто теряется, он схлопывает
# разные дела в один канонический адрес, а url в case_url уникален глобально — второе
# дело потом не сохранить вовсе.
#   name, op, case_id, delo_id — движок msudrf.ru;
#   id — mirsud.spb.ru: там номер дела стоит именно в нём
#        (/cases/detail/98/?id=2-2976%2F2026-98), а путь задаёт только участок,
#        то есть без id все дела одного участка выглядят одной карточкой.
MEANINGFUL_QUERY_PARAMS = ("name", "op", "case_id", "delo_id", "id")


def canonical_case_url(url: str) -> str:
    """Привести адрес карточки к каноническому виду.

    На одну и ту же карточку ведёт множество внешне разных строк: http и https, разный
    регистр хоста, переставленные параметры, лишний хвост. Без приведения к общему виду
    каждая такая строка выглядела бы новой карточкой — заводилась бы лишняя задача с
    походом через прокси и капчу, а в базе появлялся бы дубль.

    Что делаем: схема всегда https (порталы её поддерживают и сами туда redirect'ят),
    хост в нижний регистр, из параметров оставляем только значащие и сортируем их,
    хвостовой слеш убираем. Регистр пути НЕ трогаем — на части порталов он значим.
    """
    parts = urlsplit(normalize_url(url))
    query = [
        (key, value)
        for key, value in parse_qsl(parts.query)
        if key in MEANINGFUL_QUERY_PARAMS
    ]
    return urlunsplit(
        (
            "https",
            (parts.hostname or "").lower() + (f":{parts.port}" if parts.port else ""),
            parts.path.rstrip("/"),
            urlencode(sorted(query)),
            "",  # якорь к карточке отношения не имеет
        )
    )


# --- Идентификатор карточки, у которой на портале нет УИД ----------------------

# Приставка самодельного идентификатора карточки. Приём тот же, что у url_label
# (app/storage/html_snapshots.py), который метит папки S3 приставкой url-: по значению
# сразу видно, что это НЕ УИД с портала.
SYNTHETIC_UID_PREFIX = "nouid-"

# Сколько символов хэша оставляем в идентификаторе. 12 шестнадцатеричных знаков — это 48
# бит: на масштабе всех дел страны столкновения не ожидается, а ключ остаётся коротким и
# читаемым в логах и в именах папок S3.
SYNTHETIC_UID_HASH_LENGTH = 12


def synthetic_uid(court_code: str, url: str) -> str:
    """Идентификатор карточки, у которой УИД на портале нет вовсе.

    Такие карточки есть: УИД начали присваивать примерно с 2021 года, поэтому у архивных
    дел его нет (например, дело 2-370/4520 2011 года на sakha45.yak.msudrf.ru), а на
    отдельных порталах движка его нет и у свежих (Магаданская область). При этом УИД —
    часть ключа карточки (Case.uid) и основа uid дочерних строк, так что без какого-то
    идентификатора дело просто нечем сохранить.

    Считаем его САМИ от ссылки: у порталов без поиска по УИД адрес карточки постоянен и
    соответствует делу взаимно однозначно, поэтому такой ключ стабилен между обходами и
    известен ещё до похода на портал.

    Хэш берём от КАНОНИЧЕСКОГО адреса (canonical_case_url), а не от присланной строки:
    иначе http/https, переставленные параметры и лишний хвост дали бы разные ключи на
    одну карточку. Код суда ставим в начало для человека — чтобы ключ читался в логах и в
    именах папок S3; за однозначность отвечает хэш.

    Формат заведомо не проходит UID_PATTERN, поэтому «настоящий УИД или самодельный»
    видно по самому значению — отдельного поля в БД для этого не нужно.
    """
    digest = hashlib.sha256(canonical_case_url(url).encode("utf-8")).hexdigest()
    return f"{SYNTHETIC_UID_PREFIX}{court_code}-{digest[:SYNTHETIC_UID_HASH_LENGTH]}"


def is_synthetic_uid(uid: str) -> bool:
    """Это самодельный идентификатор карточки, а не УИД с портала?

    По нему решается, показывать ли значение наружу: в API у таких карточек uid = null
    (см. Case.public_uid), а сквозные проверки вида «первые 8 символов УИД — код суда»
    к нему неприменимы.
    """
    return (uid or "").startswith(SYNTHETIC_UID_PREFIX)
