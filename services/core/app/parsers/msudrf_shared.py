"""Общее для парсеров движка msudrf.ru: метки карточки, вкладки, даты, тип разметки.

У движка ДВЕ вёрстки карточки, и различаются они только тегами и формой таблиц — смысл
полей один и тот же:

* тип B (app/parsers/msudrf_type_b.py) — метка карточки лежит в <h2>, у таблиц есть <thead>;
* тип C (app/parsers/msudrf_type_c.py) — метка лежит в <b>, <thead> нет вовсе: шапка это
  первая строка тела, свёрстанная теми же <b>, а над ней стоит секционный заголовок
  <td colspan=N><h2>ОСНОВНЫЕ СВЕДЕНИЯ</h2></td>.

Поэтому здесь живёт всё, что у двух типов совпадает: набор меток карточки, метки судьи,
разбор дат, сопоставление названий вкладок с их телами и поиск колонки по шапке. Дублировать
это в двух парсерах нельзя: метки движок меняет одновременно на обеих вёрстках, и разъехавшиеся
копии — это молча потерянное поле у одного из типов.

Здесь же detect_page_type: тип разметки определяется по самой странице, а не по домену
портала. Так и надо: домен говорит лишь, какую вёрстку мы ОЖИДАЕМ увидеть у региона, а
отдать портал может другую (регионы подключают по домену, не открыв ни одной карточки).
"""
from datetime import date, datetime

from bs4 import BeautifulSoup, Tag


def clean(text: str) -> str:
    """Схлопнуть любые пробелы/переводы строк в один пробел и обрезать края."""
    return " ".join(text.split())


def clean_or_none(text: str) -> str | None:
    """Как clean, но пустое значение → None (в БД такому полю место NULL, а не '')."""
    return clean(text) or None


# Формат дат на портале — везде один, и в карточке, и в таблице событий.
DATE_FORMAT = "%d.%m.%Y"


def parse_date(text: str) -> date | None:
    """Разобрать дату формата ДД.ММ.ГГГГ; пустое/некорректное значение → None."""
    text = clean(text)
    if not text:
        return None
    try:
        return datetime.strptime(text, DATE_FORMAT).date()
    except ValueError:
        return None


# Вкладки: названия в ul#tabs, тела — в div#contentt. Сопоставляются только по порядку.
TABS_SELECTOR = "ul#tabs li"
# Обёртка тела вкладки бывает двух видов, и это НЕ связано с типом разметки карточки:
#   * div.tab-content — Московская область, Якутия, Орловская, Пермский край, Адыгея;
#   * div#cont1, div#cont2, … — Липецкая область (там же у самих вкладок есть id и <a>).
# Пока искали только первый, у Липецкой области (регион подключён!) разбор возвращал
# пустоту целиком: тел вкладок находилось ноль.
TAB_BODIES_SELECTOR = "div#contentt > div.tab-content"
TAB_BODIES_FALLBACK_SELECTOR = "div#contentt > div[id]"


def tab_bodies(soup: BeautifulSoup) -> dict[str, Tag]:
    """Сопоставить название вкладки с её содержимым по порядковому номеру.

    Привязать тело к названию можно только позицией: у вкладок бывают id (tab1, tab2), но
    не на всех порталах движка, а data-атрибутов и href на тело нет нигде. Лишние названия
    без тела (и наоборот) молча отбрасываем: zip обрезается по короткому, и это ровно то
    поведение, которое нужно.
    """
    names = [clean(tab.get_text()) for tab in soup.select(TABS_SELECTOR)]
    bodies = soup.select(TAB_BODIES_SELECTOR) or soup.select(TAB_BODIES_FALLBACK_SELECTOR)
    return {name: body for name, body in zip(names, bodies) if name}


def find_tab(tabs: dict[str, Tag], *prefixes: str) -> Tag | None:
    """Тело вкладки, название которой начинается с одного из prefixes.

    Именно по НАЧАЛУ названия, а не по полному совпадению: одна и та же вкладка подписана
    по-разному даже в пределах движка — «СТОРОНЫ» (Московская область, Якутия),
    «СТОРОНЫ ПО ДЕЛУ» (Пермский край), «СТОРОНЫ ПО ДЕЛУ (ТРЕТЬИ ЛИЦА)» (Адыгея). Сверка
    целиком теряла такую вкладку вместе со всеми сторонами по делу.
    """
    for name, body in tabs.items():
        if name.startswith(prefixes):
            return body
    return None


