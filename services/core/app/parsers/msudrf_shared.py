def column_index(headings: list[str], wanted: frozenset) -> int | None:
    """Номер колонки, чья шапка совпала с одной из искомых (или None, если такой нет)."""
    for index, heading in enumerate(headings):
        if heading in wanted:
            return index
    return None


# --- Тип разметки страницы -----------------------------------------------------

PAGE_TYPE_B = "B"
PAGE_TYPE_C = "C"

# Метки карточки и шапки таблиц: <h2> — тип B, <b> — тип C. Секционный заголовок типа C
# («ОСНОВНЫЕ СВЕДЕНИЯ», «СВЕДЕНИЯ О ПРИВЛЕКАЕМОМ ЛИЦЕ») тоже свёрстан <h2>, но всегда
# стоит в ячейке с colspan — по нему тип не определяем, иначе тип C опознавался бы как B.
# Селекторы перечисляют обе обёртки тела вкладки (см. TAB_BODIES_FALLBACK_SELECTOR).
_TYPE_C_LABELS = "div#contentt td > b"
_TYPE_B_LABELS = "div#contentt td:not([colspan]) > h2"


def detect_page_type(html: str) -> str | None:
    """Какой вёрсткой отдана карточка: "B", "C" или None, если это не карточка.

    Нужно потому, что тип нельзя надёжно вывести из домена: движок общий для 72 регионов,
    регионы подключают по домену, и какая из двух вёрсток окажется на портале — заранее
    неизвестно (Орловская область оказалась типом B, соседняя Пермский край — типом C).
    Ошибка в типе не падает, а тихо даёт пустой разбор, поэтому спрашиваем саму страницу.

    Сначала проверяем тип C: у него на странице есть и <b>-метки, и <h2> секционных
    заголовков, а у типа B никаких <b> в ячейках нет.
    """
    soup = BeautifulSoup(html, "lxml")
    if soup.select_one(_TYPE_C_LABELS) is not None:
        return PAGE_TYPE_C
    if soup.select_one(_TYPE_B_LABELS) is not None:
        return PAGE_TYPE_B
    return None
