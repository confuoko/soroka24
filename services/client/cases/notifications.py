"""Уведомления об изменениях по делам: вся обвязка есть, канала доставки пока нет.

## Что здесь настоящее, а что заглушка

    notify_pending()                       ← выборка, группировка, отметка. БОЕВОЕ
        └── deliver(user, case_id, changes)   ← ЗАГЛУШКА: пишет строку в лог

`deliver` — единственное место, которое изменится, когда понадобится настоящий канал (почта,
Telegram). Всё вокруг него написано и проверено как боевое: реальная выборка, реальная
группировка, реальная отметка в базе, реальные тесты.

Разделение сделано не абстракции ради. Без него подключение канала означало бы писать и
отлаживать обвязку заново — уже под давлением «нам нужны письма вчера», то есть в худший
момент. Реестра каналов, базового класса и настройки со списком бекендов здесь нет и не
будет, пока не появятся хотя бы два реальных канала (ТЗ §8 и §13).

## Порядок: сначала доставка, потом отметка

Наоборот делать нельзя. Отметили и упали — и пользователь не узнает об изменении НИКОГДА:
второй раз строка в выборку уже не попадёт. Обратный порядок в худшем случае даёт повторное
уведомление, а это несравнимо дешевле пропажи.

## Группировка

Обход находит по 5–8 изменений разом. Уведомление на каждое означало бы восемь писем подряд
про одно дело — ровно то, от чего сервис должен избавлять. Поэтому неотправленное собирается
в группы «пользователь + дело», и `deliver` зовётся один раз на группу.

`notified_at` не оглядывается на `read_at`: «не видел на сайте» и «не получал уведомления» —
разные факты. Правило «уже прочитал — не писать» осмысленно, но зависит от задержки доставки,
которой у нас пока нет; решать его надо вместе с настоящим каналом.
"""
import logging
from collections import defaultdict

from django.utils import timezone

from cases.models import UserCaseChange

logger = logging.getLogger(__name__)


# Типы изменений по-русски. Словарь, а не choices в модели: core публикует все 16 типов и
# добавит новые, а новый тип не должен ни ронять рассылку, ни требовать миграции.
DESCRIPTIONS = {
    "case_field_changed": "изменились реквизиты дела",
    "event_new": "новое событие",
    "event_updated": "событие изменилось",
    "event_removed": "событие пропало",
    "place_new": "новая запись о местонахождении",
    "place_updated": "запись о местонахождении изменилась",
    "place_removed": "запись о местонахождении пропала",
    "session_new": "назначено заседание",
    "session_updated": "заседание изменилось",
    "session_removed": "заседание отменено",
    "document_new": "новый документ",
    "document_removed": "документ пропал",
    "judge_added": "назначен судья",
    "judge_removed": "судья снят",
    "side_added": "добавлена сторона",
    "side_removed": "сторона убрана",
}


def describe(event_type: str) -> str:
    """Тип изменения человеческими словами. Незнакомый возвращается как есть.

    Именно возвращается, а не падает и не пропускается: core может начать публиковать новый
    тип раньше, чем мы про него узнаем, и лучше показать человеку сырое `session_moved`, чем
    промолчать об изменении или уронить рассылку целиком.
    """
    return DESCRIPTIONS.get(event_type, event_type)


def deliver(user, core_case_id: int, changes: list[UserCaseChange]) -> None:
    """ЗАГЛУШКА доставки: пишет в лог то, что отправила бы настоящим каналом.

    **Это единственное место, которое надо переписать, когда появится канал.** Здесь встанет
    `send_mail` (или отправка в Telegram): адресат — `user`, тема — про дело `core_case_id`,
    тело — список `changes`. Выборка, группировка, отметка «сообщено» и тесты вокруг уже
    боевые и переделки не потребуют.

    Канала сейчас нет сознательно: цепочка до unread в UI работает и проверена, а слать письма
    заказчик пока не просил. Строка в логе — не пустая формальность: по ней видно, что
    рассылка вообще дошла до доставки, и на ней проверяется группировка.

    Исключение отсюда `notify_pending` перехватывает и оставляет группу неотмеченной — так
    настоящий канал сможет упасть, ничего не потеряв.
    """
    logger.info(
        "Уведомление (заглушка) для %s по делу #%s, изменений %s: %s",
        user,
        core_case_id,
        len(changes),
        "; ".join(describe(change.event_type) for change in changes),
    )


def notify_pending(limit: int = 0) -> int:
    """Сообщить обо всём, о чём ещё не сообщали. Возвращает число доставленных групп.

    `limit` ограничивает число ГРУПП (пользователь + дело), а не строк: группа — это одно
    уведомление, и резать её пополам бессмысленно.

    Строки берём выборкой, а не из результата `fan_out`: `bulk_create(ignore_conflicts=True)`
    в consumer'е не заполняет первичные ключи, полагаться на его результат нельзя.
    """
    pending = (
        UserCaseChange.objects.filter(notified_at__isnull=True)
        .select_related("user", "subscription")
        .order_by("occurred_at", "id")
    )

    groups: dict[tuple[int, int], list[UserCaseChange]] = defaultdict(list)
    for change in pending:
        groups[(change.user_id, change.subscription_id)].append(change)

    delivered = 0
    for changes in list(groups.values())[: limit or None]:
        first = changes[0]
        try:
            deliver(first.user, first.subscription.core_case_id, changes)
        except Exception:
            # Одна неудачная группа не должна лишить уведомлений остальных. Группу НЕ
            # отмечаем — попадёт в следующий прогон. У заглушки такого не случится, у
            # настоящего канала случится обязательно.
            logger.exception(
                "Уведомление для %s по делу #%s не доставлено, попробуем позже",
                first.user, first.subscription.core_case_id,
            )
            continue

        # Отметка ПОСЛЕ доставки. Наоборот — отметили и упали — и человек не узнает об
        # изменении никогда: второй раз строка в выборку не попадёт.
        UserCaseChange.objects.filter(id__in=[change.id for change in changes]).update(
            notified_at=timezone.now()
        )
        delivered += 1

    return delivered
