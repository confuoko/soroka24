"""Формы клиентского сервиса. Пока одна.

Обычная `forms.Form`, а не `ModelForm`: то, что вводит пользователь, — не поле модели.
Ссылка или УИД превращаются в `core_case_id` только после похода core на портал, и
записывать введённое в `CaseSubscription` нечем.
"""
from django import forms


class AddCaseForm(forms.Form):
    """Одно поле на оба способа добавления дела: ссылка или УИД.

    Разбирать введённое здесь НЕ пытаемся, и это осознанно. Что именно прислали, умеет
    определять core (`app/validators.py`), и он же знает, у какого портала есть поиск по
    УИД, а у какого дело открывается только прямой ссылкой. Продублируй мы эти правила
    здесь — они разъехались бы на первом же новом портале, и клиент начал бы отклонять
    ссылки, которые core прекрасно понимает.

    Поэтому валидация тут только на пустоту, а осмысленный отказ приходит с сервера
    готовым человеческим текстом (поле `message` ответа) и показывается как есть.
    """

    query = forms.CharField(
        label="Ссылка на дело или УИД",
        max_length=1000,
        strip=True,
        widget=forms.TextInput(
            attrs={
                "size": 70,
                "autofocus": True,
                "placeholder": "https://mos-sud.ru/… или 77MS0466-01-2026-003751-93",
            }
        ),
        help_text=(
            "Ссылку на карточку дела понимают все поддержанные суды. "
            "Поиск по УИД работает только у части порталов."
        ),
    )
